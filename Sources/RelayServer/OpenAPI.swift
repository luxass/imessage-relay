import Foundation
import HummingbirdOpenAPI

/// Records declarations owned by the route files. Never opens chat.db,
/// initializes native providers, starts a listener, or invokes handlers.
public func relayOpenAPIDocument() throws -> Data {
    let routes = JSONRoutes<RelayRequestContext>()
    StatusRoutes.register(on: routes, use: { _, _ in throw DocumentationOnlyError.handlerInvoked })
    MessageRoutes.registerSend(on: routes, use: { _, _, _ in throw DocumentationOnlyError.handlerInvoked })
    return try routes.document(
        title: "imessage-relay: code-first OpenAPI prototype",
        version: "v1",
        serverURL: "http://127.0.0.1:8080",
        errorModel: ErrorPayload.self,
        bearerAuthentication: true,
        description: """
        GENERATED by swift run RelayOpenAPI. Do not edit.
        Prototype coverage: GET /v1/status and POST /v1/messages only.
        Structural schemas come from the live wire models. Destination rules,
        allowlists, permissions, and other business validation remain in the API reference.
        """
    ).json()
}

private enum DocumentationOnlyError: Error { case handlerInvoked }
